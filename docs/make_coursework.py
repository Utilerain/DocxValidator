def _make_png(width=520, height=200):
    """Схема структуры сайта: блок и три подчинённых блока (PNG без PIL)."""
    bg, border, fill = (255, 255, 255), (31, 78, 121), (222, 235, 247)
    px = [[bg] * width for _ in range(height)]

    def rect(x0, y0, x1, y1, inner=fill):
        for y in range(max(0, y0), min(height, y1)):
            for x in range(max(0, x0), min(width, x1)):
                edge = x in (x0, x1 - 1) or y in (y0, y1 - 1)
                px[y][x] = border if edge else inner

    def vline(y0, y1, x):
        for y in range(y0, y1):
            px[y][x] = border

    def hline(x0, x1, y):
        for x in range(x0, x1):
            px[y][x] = border

    rect(190, 15, 330, 45)          # главная страница
    vline(45, 70, 260)
    hline(90, 431, 70)
    for cx in (90, 260, 430):
        vline(70, 95, cx)
        rect(cx - 70, 95, cx + 70, 165, (245, 249, 252))

    def chunk(typ, data):
        return (struct.pack('>I', len(data)) + typ + data
                + struct.pack('>I', zlib.crc32(typ + data) & 0xffffffff))

    ihdr = struct.pack('>IIBBBBB', width, height, 8, 2, 0, 0, 0)
    raw = b''.join(b'\x00' + bytes(c for cell in row for c in cell)
                   for row in px)
    return (b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', ihdr)
            + chunk(b'IDAT', zlib.compress(raw)) + chunk(b'IEND', b''))


def _set_grid(section):
    """Включённая сетка текста в каждом разделе."""
    sect_pr = section._sectPr
    grid = sect_pr.find(qn('w:docGrid'))
    if grid is None:
        grid = OxmlElement('w:docGrid')
        sect_pr.append(grid)
    grid.set(qn('w:type'), 'lines')
    grid.set(qn('w:linePitch'), '360')


def _add_page_number(section):
    """Поле PAGE в правом верхнем углу, Times New Roman 10 pt."""
    header = section.header
    header.is_linked_to_previous = False
    p = header.paragraphs[0]
    p.alignment = RIGHT
    field = OxmlElement('w:fldSimple')
    field.set(qn('w:instr'), ' PAGE ')
    run = OxmlElement('w:r')
    props = OxmlElement('w:rPr')
    fonts = OxmlElement('w:rFonts')
    fonts.set(qn('w:ascii'), 'Times New Roman')
    fonts.set(qn('w:hAnsi'), 'Times New Roman')
    size = OxmlElement('w:sz')
    size.set(qn('w:val'), '20')
    props.append(fonts)
    props.append(size)
    run.append(props)
    text = OxmlElement('w:t')
    text.text = '2'
    run.append(text)
    field.append(run)
    p._p.append(field)


def para(doc, text='', align=None, bold=False, first_indent=None,
         spacing=None, size=None, page_break=False):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    if first_indent is not None:
        p.paragraph_format.first_line_indent = first_indent
    if spacing is not None:
        p.paragraph_format.line_spacing = spacing
    if page_break:
        p.paragraph_format.page_break_before = True
    if text:
        run = p.add_run(text)
        if bold:
            run.bold = True
        if size is not None:
            run.font.size = size
    return p


